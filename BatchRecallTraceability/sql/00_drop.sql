-- Batch Recall Traceability : drop all objects (Oracle, run in SQL*Plus)
-- Safe to run on an empty schema: missing objects are ignored.
SET SERVEROUTPUT ON
BEGIN
  FOR t IN (SELECT 'RECALL_LOT' n FROM dual UNION ALL SELECT 'RECALL' FROM dual
            UNION ALL SELECT 'SHIPMENT_LINE' FROM dual UNION ALL SELECT 'SHIPMENT' FROM dual
            UNION ALL SELECT 'CUSTOMER' FROM dual UNION ALL SELECT 'QUALITY_TEST' FROM dual
            UNION ALL SELECT 'BATCH_INPUT' FROM dual UNION ALL SELECT 'PRODUCED_LOT' FROM dual
            UNION ALL SELECT 'RAW_LOT' FROM dual UNION ALL SELECT 'LOT' FROM dual
            UNION ALL SELECT 'PRODUCTION_BATCH' FROM dual UNION ALL SELECT 'EMPLOYEE' FROM dual
            UNION ALL SELECT 'ITEM' FROM dual UNION ALL SELECT 'SUPPLIER_PHONE' FROM dual
            UNION ALL SELECT 'SUPPLIER' FROM dual) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.n || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION WHEN OTHERS THEN NULL;
    END;
  END LOOP;
  FOR v IN (SELECT 'LOT_STOCK' n FROM dual UNION ALL SELECT 'LOT_EXPIRY' FROM dual) LOOP
    BEGIN EXECUTE IMMEDIATE 'DROP VIEW ' || v.n; EXCEPTION WHEN OTHERS THEN NULL; END;
  END LOOP;
  BEGIN EXECUTE IMMEDIATE 'DROP SEQUENCE recall_seq'; EXCEPTION WHEN OTHERS THEN NULL; END;
END;
/
